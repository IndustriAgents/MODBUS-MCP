"""Native Modbus connection required by application operations."""

from collections.abc import Awaitable, Callable
from typing import Any, Protocol


class ModbusTransportPort(Protocol):
    """Injected native invocation, recovery and version-specific addressing."""

    def unit(self, client: Any, slave_id: int) -> dict[str, int]: ...

    async def request(
        self,
        ctx: Any,
        app: Any,
        op: str,
        call_factory: Callable[[], Awaitable[Any]],
        max_retries: int | None = None,
        *,
        write: bool = False,
        details: dict[str, Any] | None = None,
        check: Callable[[Any], dict[str, Any] | None] | None = None,
    ) -> tuple[Any | None, str | None, float, int]: ...


class ModbusClientPort(Protocol):
    connected: bool

    async def connect(self) -> bool: ...
    def close(self) -> None: ...
    async def read_holding_registers(self, *args: Any, **kwargs: Any) -> Any: ...
    async def read_input_registers(self, *args: Any, **kwargs: Any) -> Any: ...
    async def read_coils(self, *args: Any, **kwargs: Any) -> Any: ...
    async def read_discrete_inputs(self, *args: Any, **kwargs: Any) -> Any: ...
    async def read_device_information(self, *args: Any, **kwargs: Any) -> Any: ...
    async def write_register(self, *args: Any, **kwargs: Any) -> Any: ...
    async def write_registers(self, *args: Any, **kwargs: Any) -> Any: ...
    async def write_coil(self, *args: Any, **kwargs: Any) -> Any: ...
    async def write_coils(self, *args: Any, **kwargs: Any) -> Any: ...
    async def mask_write_register(self, *args: Any, **kwargs: Any) -> Any: ...
